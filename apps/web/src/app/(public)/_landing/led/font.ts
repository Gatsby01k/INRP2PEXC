/** Words as one strip of dots, a dark column between glyphs; anything the face lacks is a space. */
export function strip(text: string): Bitmap {
  const glyphs = [...text.toUpperCase()].map((c) => G[c] ?? G[' ']!);
  return Array.from({ length: GLYPH_ROWS }, (_, r) => glyphs.map((g) => `${g[r]}.`).join(''));
}

/** A bitmap set on `rows` rows, in the middle. */
export function onRows(bitmap: Bitmap, rows: number): Bitmap {
  const width = Math.max(1, ...bitmap.map((r) => r.length));
  const top = Math.floor((rows - bitmap.length) / 2);
  return Array.from({ length: rows }, (_, r) => (bitmap[r - top] ?? '').padEnd(width, '.'));
}
